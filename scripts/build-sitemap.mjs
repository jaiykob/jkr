/**
 * Generates sitemap.xml from the pages that actually exist.
 *
 *   node scripts/build-sitemap.mjs           # rewrite sitemap.xml
 *   node scripts/build-sitemap.mjs --check   # fail if a page is missing or extra (npm test)
 *
 * Carried over from Scoops Co., where the sitemap was once hand kept: a page
 * missing from it is a page Google may never find, and a typed lastmod that
 * lies teaches Google to stop trusting the file.
 *
 *   - Every public .html page without a noindex robots meta is listed; the
 *     dashboard (jkr/), checkout, thanks and 404 never are.
 *   - lastmod is the date of the last git commit that touched the page, so it
 *     is a fact. A page not committed yet gets today.
 *   - --check compares the list of pages, not the dates: a date changes on
 *     every commit, and a check that is red after every commit gets ignored.
 *
 * The address comes from api/_lib/site.js, so set-domain moves it too.
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import site from '../api/_lib/site.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const OUT = path.join(ROOT, 'sitemap.xml');
// Folders that are not public pages (or not pages at all).
const SKIP = new Set(['node_modules', '.git', '.vercel', '.superpowers', '.claude', '.agents', 'jkr', 'docs', 'api', 'scripts', 'content', 'agent', 'marketing', 'data', 'db']);

/** Every indexable page, as a path from the site root. */
export function pages() {
  const out = [];
  const walk = (dir) => {
    for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
      const rel = dir ? `${dir}/${e.name}` : e.name;
      if (e.isDirectory()) { if (!SKIP.has(e.name)) walk(rel); continue; }
      if (!e.name.endsWith('.html')) continue;
      if (/<meta name="robots" content="noindex/.test(fs.readFileSync(path.join(ROOT, rel), 'utf8'))) continue;
      out.push(rel);
    }
  };
  walk('');
  // The homepage first, then the hub, then everything else by name.
  const rank = (p) => (p === 'index.html' ? 0 : p === 'service-areas.html' ? 1 : 2);
  return out.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
}
export const urlOf = (rel) => `${site.SITE_URL}/${rel.replace(/(^|\/)index\.html$/, '$1')}`;

function lastmod(rel) {
  const r = spawnSync('git', ['log', '-1', '--format=%cs', '--', rel], { cwd: ROOT, encoding: 'utf8' });
  return (r.status === 0 && r.stdout.trim()) || new Date().toISOString().slice(0, 10);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();

function main() {
  const list = pages();
  const xml = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- GENERATED by scripts/build-sitemap.mjs. Do not edit: run npm run build. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...list.map((rel) => `  <url><loc>${urlOf(rel)}</loc><lastmod>${lastmod(rel)}</lastmod></url>`),
    '</urlset>',
    '',
  ].join('\n');

  const locs = (s) => [...s.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]).join('\n');
  const before = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (check) {
    if (locs(before) !== locs(xml)) {
      console.error('build-sitemap --check: sitemap.xml does not list exactly the indexable pages. Run npm run build.');
      process.exit(1);
    }
    console.log(`build-sitemap --check: OK, ${list.length} pages`);
  } else {
    fs.writeFileSync(OUT, xml);
    console.log(`build-sitemap: wrote sitemap.xml (${list.length} pages)`);
  }
}
