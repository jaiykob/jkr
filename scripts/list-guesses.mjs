/**
 * npm run guesses            write GUESSES.md: every placeholder guess on the site
 * npm run guesses -- --check fail if GUESSES.md is out of date (runs in npm test)
 *
 * The founder's rule (2026-10-07): guess everything for now, show it in red
 * with an asterisk, and keep the list for later. Three kinds of guess:
 *
 *   flags     GUESS in pricing.config.mjs. Each true flag marks a whole table
 *             (prices, travel zones, the base point) red wherever it prints.
 *   source    a comment or doc line carrying the marker GUESS* followed by
 *             what was guessed. Use it in code, SQL, Markdown, anything.
 *   pages     text wrapped in class="guess" in an HTML page (red on screen).
 *
 * The list has no line numbers or dates on purpose, so it only changes when a
 * guess does, and --check stays quiet the rest of the time.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'GUESSES.md');
const check = process.argv.includes('--check');
const MARK = 'GUESS' + '*';   // split so this file doesn't list itself

const SKIP_DIRS = new Set(['node_modules', '.git', '.superpowers', '.vercel', '.claude', '.agents', 'data']);
const SKIP_FILES = new Set(['GUESSES.md', 'scripts/list-guesses.mjs', 'scripts/score.mjs', 'css/guess.css']);
const SKIP_PREFIX = ['docs/superpowers/'];   // plans and specs describe the convention
const TEXT = /\.(html|js|mjs|cjs|css|md|sql|json|txt|yml)$/;

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, e.name);
    const rel = path.relative(ROOT, abs).split(path.sep).join('/');
    if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) walk(abs, out); continue; }
    if (!TEXT.test(e.name) || SKIP_FILES.has(rel) || SKIP_PREFIX.some((p) => rel.startsWith(p))) continue;
    out.push(rel);
  }
  return out;
}

const { GUESS } = await import(pathToFileURL(path.join(ROOT, 'pricing.config.mjs')).href);
const FLAG_NOTES = {
  prices: 'The load prices (`PRICE_TABLE` in `pricing.config.mjs`): every load size, one-time and monthly.',
  zones:  'The travel zones (`ZONES` in `pricing.config.mjs`): the mile bands and the fee for each zone.',
  base:   'The base point (`BASE` in `pricing.config.mjs`): Gresham city center, not the real yard. Moving it means re-running `node scripts/measure-zips.mjs`.',
};

const files = walk(ROOT).sort();
const source = [];
const pages = [];
const clean = (s) => s.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
for (const f of files) {
  const s = fs.readFileSync(path.join(ROOT, f), 'utf8');
  for (const line of s.split(/\r?\n/)) {
    const i = line.indexOf(MARK);
    if (i < 0) continue;
    const what = line.slice(i + MARK.length).replace(/^[:\s]+/, '').replace(/\s*(\*\/|-->)\s*$/, '').trim();
    source.push(`- [ ] \`${f}\`: ${what || '(no note)'}`);
  }
  if (f.endsWith('.html')) {
    const found = [...s.matchAll(/<span class="[^"]*\bguess\b[^"]*"[^>]*>([\s\S]*?)<\/span>/g)].map((m) => clean(m[1])).filter(Boolean);
    if (found.length) pages.push(`- \`${f}\` (${found.length}): ${[...new Set(found)].join(', ')}`);
  }
}

const flags = Object.entries(GUESS).filter(([, on]) => on).map(([k]) => `- [ ] **${k}** (\`GUESS.${k}\`): ${FLAG_NOTES[k] || ''}`);
const md = [
  '# Guesses to replace',
  '',
  'Generated by `npm run guesses`. Do not edit by hand.',
  '',
  'Everything below is a placeholder we guessed so the site could be built',
  '(founder, 2026-10-07: "just guess everything for now and put it in red text',
  'with asterisk to store for later"). On the site each one shows **red with an',
  'asterisk**. Replace the value, then clear its mark: set the flag to `false`',
  'in `pricing.config.mjs` (and run `npm run build:pricing`), delete the marker',
  'comment, or drop `class="guess"`. Then run `npm run guesses` again.',
  '',
  '## Whole tables (flags in pricing.config.mjs)',
  '',
  ...(flags.length ? flags : ['None. Every table holds real numbers.']),
  '',
  '## Marked in the source',
  '',
  ...(source.length ? source : ['None.']),
  '',
  '## Red on the pages right now',
  '',
  ...(pages.length ? pages : ['None.']),
  '',
].join('\n');

const before = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
if (check) {
  if (before !== md) { console.error('STALE: GUESSES.md does not match the guesses on the site.\nRun: npm run guesses'); process.exit(1); }
  console.log(`check-guesses: GUESSES.md current (${flags.length} flags, ${source.length} marked, ${pages.length} pages)`);
  process.exit(0);
}
fs.writeFileSync(OUT, md);
console.log(`guesses: wrote GUESSES.md (${flags.length} flags, ${source.length} marked in source, ${pages.length} pages with red text)`);
