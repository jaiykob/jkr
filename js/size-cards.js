/* Size cards: the five load sizes as cards with a photo, a name, what fits
   and the price. The card HTML is GENERATED by scripts/build-pricing.mjs from
   LOADS and PRICES (classes .size-card, .size-photo, .size-name, .size-note,
   .size-price, .size-travel), so this file holds no prices and no sizes.

   Shared by the order page (book/quote.html, cards are buttons you pick) and
   the homepage (cards are links to the order page with that size picked), so
   it knows nothing about either page.

   SizeCards.mount(root, { onPick(row, how), words: { none, suffix }, selector }) -> {
                          (words: another language; selector: the cards, '.size-card' by
                          default, '.h-ticket' for the homepage's price ticket)
     pick(row)            mark one card picked (aria-pressed), no callback
     setTravel(trip, guess)  the travel line on every card: "+ travel" until the
                          ZIP is known (trip null), then the fee or "No travel charge"
     row()                the picked row, or null
   }                                                                          */
(function () {
  'use strict';
  function fmt(c) { return '$' + (c / 100).toFixed(2); }

  function mount(root, opts) {
    opts = opts || {};
    var W = opts.words || { none: 'No travel charge', suffix: ' travel' };
    if (!root) return null;
    var cards = [].slice.call(root.querySelectorAll(opts.selector || '.size-card'));
    var current = null;
    var rowOf = function (card) { return parseInt(card.getAttribute('data-size'), 10); };

    function pick(row) {
      current = row == null || isNaN(row) ? null : +row;
      cards.forEach(function (c) {
        if (c.tagName === 'BUTTON') c.setAttribute('aria-pressed', String(rowOf(c) === current));
      });
    }
    cards.forEach(function (c) {
      // A link card (the homepage) just goes to the order page.
      if (c.tagName !== 'BUTTON') return;
      c.addEventListener('click', function () {
        pick(rowOf(c));
        if (opts.onPick) opts.onPick(current, 'tap');
      });
    });

    // The first text each card shipped with ("+ travel"), to go back to.
    var plain = cards.map(function (c) { var t = c.querySelector('.size-travel'); return t ? t.textContent : ''; });
    function setTravel(trip, guess) {
      cards.forEach(function (c, i) {
        var t = c.querySelector('.size-travel');
        if (!t) return;
        t.textContent = '';
        if (!trip) { t.textContent = plain[i]; return; }
        if (!trip.cents) { t.textContent = W.none; return; }
        var fee = document.createElement('span');
        if (guess) fee.className = 'guess';
        fee.textContent = fmt(trip.cents);
        t.appendChild(document.createTextNode('+ '));
        t.appendChild(fee);
        t.appendChild(document.createTextNode(W.suffix));
      });
    }

    return { pick: pick, setTravel: setTravel, row: function () { return current; }, cards: cards };
  }

  window.SizeCards = { mount: mount };
})();
